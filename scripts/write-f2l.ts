import { readFileSync, writeFileSync } from 'node:fs';
import { applyAlg, solved } from '../src/lib/core/cube';
import { invert } from '../src/lib/core/alg';

const algs: string[] = JSON.parse(readFileSync('/tmp/f2l9.json', 'utf8'));
const GROUPS = ['Both in U layer', 'Corner in slot, edge in U', 'Edge in slot, corner in U', 'Both in slot'];
function group(alg: string) {
  const st = applyAlg(solved(), invert(alg));
  const at = (cols: number[]) => {
    const need = [...cols].sort().join();
    const byPos = new Map<string, number[]>();
    for (const s of st) byPos.set(s.p.join(), [...(byPos.get(s.p.join()) ?? []), s.c]);
    for (const [p, c] of byPos) if (c.length === cols.length && [...c].sort().join() === need) return p.split(',').map(Number);
    throw new Error('piece not found');
  };
  const corner = at([1, 2, 4]), edge = at([2, 4]);
  const cU = corner[1] === 1, eU = edge[1] === 1;
  return cU && eU ? 0 : !cU && eU ? 1 : cU && !eU ? 2 : 3;
}
const rows = algs.map(a => ({ a, g: group(a) })).sort((x, y) => x.g - y.g || x.a.split(' ').length - y.a.split(' ').length || x.a.localeCompare(y.a));
const body = rows.map((r, i) => `  f(${i + 1}, ${r.g}, ${JSON.stringify(r.a)}),`).join('\n');
writeFileSync('src/lib/data/f2l-fr.ts', `import type { CaseDef } from './types';
export const F2L_GROUPS = ${JSON.stringify(GROUPS)};
const f = (n: number, g: number, alg: string): CaseDef => ({ id: \`F2L-\${n}\`, set: 'F2L', name: \`F2L \${n}\`, alg, group: F2L_GROUPS[g], slot: 'FR' });
// Generated by scripts/gen-f2l.ts: for each of the 41 front-right-slot cases, the shortest solution found using only R, U and F turns
// (search depth 9). These are valid and short but not always the nicest to execute; replace them with your preferred algs in the Library.
export const F2L_FR: CaseDef[] = [
${body}
];
`);
